# -*- coding: utf-8 -*-
# ==============================================================================
# 文件: __init__.py
# 归属: updater_app 更新助手包（独立打包为 update.exe,与主程序完全解耦）
# ------------------------------------------------------------------------------
# 文件用途:
#   updater_app 包的初始化入口模块;本包是一个独立运行的软件更新助手程序,
#   负责检测新版本、下载更新包、解压安装并重启主程序;不依赖主程序 runtime 层
#   任何模块,仅依赖通用基础设施（infrastructure）与自身内部模块。
# ------------------------------------------------------------------------------
# 架构定位:
#   独立可执行程序（update.exe）的根包;与主程序（main.exe）完全解耦,
#   通过任务 JSON 文件（task json）接收主程序传入的更新参数;
#   启动后独立运行,完成更新后重启主程序。
#   在整体软件架构中属于"更新助手"子系统,与主程序是平级关系。
# ------------------------------------------------------------------------------
# 核心功能:
#   1. bootstrap.py        —— 启动引导模块,解析任务 JSON,启动更新窗口
#   2. updater_main.py     —— 更新助手主入口函数,装配 MVC 三层
#   3. controller/         —— 更新流程控制器（检测/下载/安装编排）
#   4. model/              —— 更新数据模型（版本信息、配置管理）
#   5. view/               —— 更新窗口 UI（用户交互界面）
#   6. workers/            —— 后台工作线程（版本检测、下载、安装）
#   7. installer.py        —— 安装器（解压更新包、替换文件、重启主程序）
# ------------------------------------------------------------------------------
# 职责边界:
#   - 本文件仅作为包初始化入口,不包含任何运行时代码
#   - 不对外导出任何业务类或函数,仅通过子包层级暴露 API
#   - 所有业务逻辑均在子模块中实现,保持包入口的纯净性
# ------------------------------------------------------------------------------
# 线程模型:
#   本模块为包初始化模块,无运行时代码;各子模块各自管理线程。
#   导入本包时仅执行模块级代码（常量定义、导入等）,不创建线程。
# ------------------------------------------------------------------------------
# 依赖关系:
#   - 标准库: 无
#   - 第三方: 无
#   - 项目内: infrastructure（通用基础设施,单向依赖）
# ==============================================================================
