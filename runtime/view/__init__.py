# 明确声明本包对外公开的符号,控制 `from runtime.view import *` 的导入范围
# 仅导出核心视图类与模块,内部辅助函数/私有变量不对外暴露
__all__ = [
    "MainWindow",       # 主窗口视图类 - 应用程序主界面
    "common_dialog",    # 通用对话框模块 - 统一消息提示框入口
]
