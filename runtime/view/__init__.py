# ==============================================================================
# 【runtime.view 包初始化文件】__init__.py
# ==============================================================================
# 文件用途:
#   1. 声明 runtime/view 目录为一个 Python 包(package),使该目录下的所有视图模块
#      (如 main_window、common_dialog 等)可被上层 controller 通过标准包导入方式引用。
#   2. 作为 View 层的统一入口,集中导出核心视图类,简化外部 import 路径。
#   3. 本文件不包含任何业务逻辑,仅作为包标识与导出接口存在。
# ------------------------------------------------------------------------------
# 架构定位 (MVC 模式):
#   - 所属层级: View 层(视图层)
#   - 上游调用方: Controller 层(如 MainController 等业务控制器)
#   - 下游依赖: 无(本包是最底层的纯UI层,不依赖任何业务/数据模块)
#   - 职责边界: 仅负责界面渲染与用户交互事件的信号发射,不直接操作数据
# ------------------------------------------------------------------------------
# 核心功能:
#   1. 包标识: 使 runtime/view 目录成为 Python 可导入包
#   2. 模块导出: 统一导出 MainWindow、common_dialog 等视图组件
#   3. 命名空间: 为所有视图组件提供统一的 runtime.view 命名空间
# ------------------------------------------------------------------------------
# MVC 定位:
#   - Model(模型层):      无(本包不涉及数据)
#   - View(视图层):       本包整体,负责所有UI界面的渲染与交互
#   - Controller(控制层): 调用方,负责连接 View 与 Model,处理业务逻辑
# ------------------------------------------------------------------------------
# UI 设计规范:
#   - 所有视图类继承自 PySide6 的 QWidget/QMainWindow 等基类
#   - 所有用户操作通过 Qt Signal 信号向外发射,由 Controller 接收处理
#   - 所有界面数据回填通过 Controller 调用 View 的公开方法完成
#   - 严格禁止 View 层直接 import 业务模块(service/comm_tools/infrastructure)
#   - 严格禁止 View 层管理后台线程(QThread/Worker)
#   - 严格禁止 View 层直接读写配置文件或发起网络请求
# ------------------------------------------------------------------------------
# 包含模块:
#   - main_window:    主窗口视图类 MainWindow,包含签到工具、文件传输、配置管理三大Tab
#   - common_dialog:  通用对话框工具模块,提供统一的消息提示框入口
# ==============================================================================

# =====** 视图模块导入 =====**
# 从当前包导入主窗口视图类 MainWindow,供外部通过 `from runtime.view import MainWindow` 使用
from runtime.view.main_window import MainWindow

# 从当前包导入通用对话框模块,供外部通过 `from runtime.view import common_dialog` 使用
from runtime.view import common_dialog

