# -*- coding: utf-8 -*-
# ==============================================================================
# 文件名称: __init__.py
# 文件路径: runtime/controller/__init__.py
# ------------------------------------------------------------------------------
# 文件用途:
#   runtime.controller 包的初始化文件,作为控制器层(Controller Layer)的包入口.
#   该文件负责统一导出包内所有控制器类,使外部调用方可以通过
#   `from runtime.controller import XXX` 的方式直接导入所需控制器,
#   而无需关心控制器模块的内部文件结构.
# ------------------------------------------------------------------------------
# 架构定位:
#   本包在整个应用的MVC架构中属于[Controller层],位于View层(视图)
#   与Model/Worker层(数据模型/后台工作线程)之间,承担以下核心桥梁作用:
#
#   ┌─────────────────────────────────────────────────────────┐
#   │                    View 层(视图)                       │
#   │   main_window / common_dialog / 各Tab页面               │
#   └─────────────────────┬───────────────────────────────────┘
#                         │ 信号(Signal)→ 用户操作事件
#   ┌─────────────────────▼───────────────────────────────────┐
#   │              Controller 层(本包)                        │
#   │   AppStarter / MainController / FileTransferController  │
#   └─────────────────────┬───────────────────────────────────┘
#                         │ 方法调用 → 业务逻辑编排
#   ┌─────────────────────▼───────────────────────────────────┐
#   │         Model 层(数据) / Worker 层(后台线程)          │
#   │   MainModel / SignMailWorker / VersionCheckWorker 等    │
#   └─────────────────────────────────────────────────────────┘
# ------------------------------------------------------------------------------
# 核心功能:
#   1. 统一导出控制器类,简化外部导入路径
#   2. 定义控制器层对外暴露的公共API(通过 __all__ 声明)
#   3. 作为控制器模块的聚合入口,隐藏内部模块组织细节
# ------------------------------------------------------------------------------
# 边界职责:
#   - 本文件仅负责导入与导出,不包含任何业务逻辑
#   - 不创建任何控件、不操作UI、不读写数据
#   - 所有实际的控制逻辑均分散在各子模块中(app_starter、main_controller 等)
# ------------------------------------------------------------------------------
# MVC定位:
#   Controller层入口 - 负责聚合所有控制器组件,供上层(如app_bootstrap)
#   统一调用.本文件本身不直接参与MVC交互,仅作为包的门户存在.
# ------------------------------------------------------------------------------
# 包含组件(通过本文件导出的控制器):
#   - MainController:        主窗口控制器,管理主窗口所有业务逻辑
#   - FileTransferController: 文件传输Tab控制器,管理上传下载功能
#
# 注: AppStarter 虽然也属于控制器层,但其定位是应用启动流程编排器,
#     通常由 app_bootstrap 直接导入使用,不通过本包统一导出.
# ==============================================================================

# 导入 FileTransferController 类 —— 文件传输Tab控制器,负责管理文件上传下载业务
from .file_transfer_controller import FileTransferController
# 导入 MainController 类 —— 主窗口控制器,负责主窗口所有业务逻辑的编排与协调
from .main_controller import MainController

# __all__ 变量定义了当使用 `from runtime.controller import *` 时
# 会被导入的公共符号列表,同时也作为本包对外公开API的正式声明
__all__ = ["MainController", "FileTransferController"]
