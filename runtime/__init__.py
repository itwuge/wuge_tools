# -*- coding: utf-8 -*-
# ==============================================================================
# 文件: __init__.py
# 归属: runtime 运行时基础设施层 —— 包初始化与对外导出入口
# ------------------------------------------------------------------------------
# 文件用途:
#   runtime 运行时包的对外导出入口;将包内核心基础设施类聚合到包命名空间,
#   对上(上层模块/main.py)提供统一、稳定的导入路径,避免直接引用内部子模块路径.
# ------------------------------------------------------------------------------
# 架构定位:
#   runtime 包的包初始化文件;只做同层子模块的聚合再导出,自身不含任何业务逻辑;
#   上层统一通过 from runtime import AppBootstrap 使用基础设施类,禁止直接引用
#   下划线开头的私有成员.
#
#   关联组件:
#     - 上游: main.py、上层业务模块
#     - 下游: .app_bootstrap(同包子模块)
# ------------------------------------------------------------------------------
# 核心功能:
#   1. 聚合导出全局应用启动引导器(AppBootstrap)
#   2. 聚合导出全局业务异常基类(AppBusinessError)
#   3. 通过本文件提供的符号,上层无需感知 app_bootstrap 子模块的存在
# ------------------------------------------------------------------------------
# 职责边界:
#   - 仅负责符号聚合导出,不包含任何运行时代码
#   - 不做初始化操作,所有初始化逻辑由各子模块内部完成
#   - __all__ 显式划定对外公开 API 边界
# ------------------------------------------------------------------------------
# 线程模型:
#   本模块无运行时代码,仅在 import 时执行一次符号聚合导出,不存在多线程并发问题.
# ------------------------------------------------------------------------------
# 依赖关系:
#   - 标准库: 无
#   - 第三方: 无
#   - 项目内: .app_bootstrap(同包子模块)
# ==============================================================================

# ==============================================================================
# runtime 包对外公开导出区域
# ==============================================================================

# ---------------- app_bootstrap.py 对外公开导出 ----------------
# 从 app_bootstrap 子模块导入全局应用启动引导器与业务异常基类
# AppBootstrap: MVC 应用全局启动引导器,管理日志/Qt/预检/迁移/资源释放等完整生命周期
# AppBusinessError: 全局应用业务异常基类,所有业务层自定义异常均继承此类
from .app_bootstrap import AppBootstrap, AppBusinessError  # 导出启动引导器与业务异常基类

# 显式声明包的公开符号表,控制 from runtime import * 的导出范围,形成清晰的 API 边界
__all__ = [  # 显式声明包的公开符号表:控制 from runtime import * 的导出范围,形成 API 边界
    # app_bootstrap —— 应用启动引导与全局基础设施
    "AppBootstrap",  # 全局应用启动引导器:管理日志初始化/Qt应用创建/启动预检/数据迁移/资源释放
    "AppBusinessError",  # 全局业务异常基类:所有业务层自定义异常的父类,携带 code 与 message
]
