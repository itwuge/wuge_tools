# -*- coding: utf-8 -*-  # 指定源文件编码为 UTF-8,支持中文字符
# ==============================================================================
# 文件: __init__.py
# 归属: runtime/model 业务模型层(MVC-M) —— 包初始化与对外导出
# ------------------------------------------------------------------------------
# 文件用途:
#   runtime.model 包初始化文件——纯数据/业务状态层(无 Qt 依赖),统一对外导出
#   模型层公共类.
# ------------------------------------------------------------------------------
# 架构定位:
#   MVC 中的 Model 包;供 controller 等上层直接以 from runtime.model import ...
#   方式使用,包内模块(app_config 通用配置、account_store 账号存储、main_model
#   主模型)不在此暴露细节.
#
#   关联组件:
#     - 上游: controller、workers 等上层
#     - 下游: .main_model(同包子模块)
# ------------------------------------------------------------------------------
# 核心功能:
#   1. 作为 Python 包标识文件,使 runtime/model 目录成为可导入的包
#   2. 集中导出 Model 层对外公开的类与异常,屏蔽包内各模块的实现细节
#   3. 通过 __all__ 白名单控制 from runtime.model import * 的导出范围
# ------------------------------------------------------------------------------
# 职责边界:
#   - 本文件为纯包初始化模块,不直接进行数据持久化操作
#   - 实际持久化能力由各子模块(app_config/account_store/main_model 等)提供
#   - 仅导出 MainModel 与 ModelBusinessError
# ------------------------------------------------------------------------------
# 线程模型:
#   本模块无运行时代码,仅在 import 时执行一次符号聚合导出,不存在多线程并发问题.
# ------------------------------------------------------------------------------
# 依赖关系:
#   - 标准库: 无
#   - 第三方: 无
#   - 项目内: runtime.model.main_model(MainModel 主模型类、
#             ModelBusinessError 业务异常类)
# ==============================================================================
# =========** [包初始化]Model =========
# 从主模型模块导入两个公共符号,作为整个 model 包的对外门面
from .main_model import MainModel, ModelBusinessError  # 主模型类 + 业务异常类,供上层 controller 直接使用

# 包对外公开符号白名单:执行 from runtime.model import * 时仅导出以下两个名字
# 其余内部模块(如 app_config/account_store/sign_tools/update_launcher)不直接暴露
__all__ = ["MainModel", "ModelBusinessError"]  # 明确控制包的公共 API 边界
